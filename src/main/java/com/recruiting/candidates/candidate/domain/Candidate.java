package com.recruiting.candidates.candidate.domain;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.Collections;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import org.hibernate.annotations.UuidGenerator;

/**
 * Aggregate root for a candidate. State changes go through intention-revealing methods ({@link #register},
 * {@link #updateProfile}, {@link #changeStatus}) so invariants such as the status workflow cannot be bypassed.
 */
@Entity
@Table(name = "candidate")
public class Candidate {

    /** UUIDv7: not enumerable (unlike sequential ids) yet time-ordered, which keeps B-tree inserts cheap. */
    @Id
    @GeneratedValue
    @UuidGenerator(style = UuidGenerator.Style.VERSION_7)
    private UUID id;

    @Column(name = "first_name", nullable = false, length = 100)
    private String firstName;

    @Column(name = "last_name", nullable = false, length = 100)
    private String lastName;

    @Column(name = "email", nullable = false, length = 254)
    private String email;

    @Column(name = "phone", length = 20)
    private String phone;

    @Column(name = "current_title", length = 150)
    private String currentTitle;

    @Column(name = "current_company", length = 150)
    private String currentCompany;

    @Column(name = "city", length = 100)
    private String city;

    @Column(name = "country", length = 2)
    private String country;

    @Column(name = "years_of_experience", nullable = false)
    private int yearsOfExperience;

    @Column(name = "notice_period_days")
    private Integer noticePeriodDays;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private CandidateStatus status;

    @ElementCollection
    @CollectionTable(name = "candidate_skill", joinColumns = @JoinColumn(name = "candidate_id"))
    @Column(name = "skill", nullable = false, length = 50)
    private Set<String> skills = new HashSet<>();

    /** Generated by the database from name, email, title and company; mapped read-only so searches can use it. */
    @Column(name = "search_text", insertable = false, updatable = false)
    private String searchText;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /** Set explicitly on every change (including skills-only edits) from the injected clock. */
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** Wrapper type on purpose: a null version tells Spring Data the entity is new (persist, not merge). */
    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    protected Candidate() {
        // for JPA
    }

    /** New candidates always enter the pipeline as {@link CandidateStatus#NEW}. */
    public static Candidate register(CandidateProfile profile, Instant now) {
        Candidate candidate = new Candidate();
        candidate.status = CandidateStatus.NEW;
        candidate.createdAt = now;
        candidate.applyProfile(profile, now);
        return candidate;
    }

    /** Replaces all profile fields. The status is deliberately not part of the profile. */
    public void updateProfile(CandidateProfile profile, Instant now) {
        applyProfile(profile, now);
    }

    /**
     * Moves the candidate to {@code target} if the workflow allows it.
     *
     * @return the previous status, for the history record
     * @throws InvalidStatusTransitionException if the move is not allowed
     */
    public CandidateStatus changeStatus(CandidateStatus target, Instant now) {
        if (!status.canTransitionTo(target)) {
            throw new InvalidStatusTransitionException(status, target);
        }
        CandidateStatus previous = status;
        status = target;
        updatedAt = now;
        return previous;
    }

    private void applyProfile(CandidateProfile profile, Instant now) {
        this.firstName = profile.firstName();
        this.lastName = profile.lastName();
        this.email = profile.email();
        this.phone = profile.phone();
        this.currentTitle = profile.currentTitle();
        this.currentCompany = profile.currentCompany();
        this.city = profile.city();
        this.country = profile.country();
        this.yearsOfExperience = profile.yearsOfExperience();
        this.noticePeriodDays = profile.noticePeriodDays();
        // Mutate in place so Hibernate only deletes/inserts the skill rows that actually changed.
        this.skills.retainAll(profile.skills());
        this.skills.addAll(profile.skills());
        this.updatedAt = now;
    }

    public UUID getId() {
        return id;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public String getEmail() {
        return email;
    }

    public String getPhone() {
        return phone;
    }

    public String getCurrentTitle() {
        return currentTitle;
    }

    public String getCurrentCompany() {
        return currentCompany;
    }

    public String getCity() {
        return city;
    }

    public String getCountry() {
        return country;
    }

    public int getYearsOfExperience() {
        return yearsOfExperience;
    }

    public Integer getNoticePeriodDays() {
        return noticePeriodDays;
    }

    public CandidateStatus getStatus() {
        return status;
    }

    public Set<String> getSkills() {
        return Collections.unmodifiableSet(skills);
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public Long getVersion() {
        return version;
    }
}
